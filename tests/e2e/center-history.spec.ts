import { expect, test } from '@playwright/test'

test('relative centers, application Back and browser Forward keep one history', async ({ page }) => {
  await page.goto('/')
  await page.locator('svg [data-person-id="I2"]').press('Enter')
  await expect(page).toHaveURL(/\/tree\/I2$/)
  await page.locator('svg [data-person-id="I3"]').first().press('Enter')
  await expect(page).toHaveURL(/\/tree\/I3$/)
  await page.getByRole('button', { name: 'Назад', exact: true }).click()
  await expect(page).toHaveURL(/\/tree\/I2$/)
  await page.goBack()
  await expect(page).toHaveURL(/\/tree\/I1$/)
  await page.goForward()
  await expect(page).toHaveURL(/\/tree\/I2$/)
  await page.getByRole('link', { name: 'До мене', exact: true }).click()
  await expect(page.locator('svg [data-center="true"]')).toHaveAttribute('data-person-id', 'I1')
  await page.getByRole('button', { name: 'Назад', exact: true }).click()
  await expect(page).toHaveURL(/\/tree\/I2$/)
})

test('repeated clicks and selecting the current address do not add duplicate steps', async ({ page }) => {
  await page.goto('/tree/I1')
  await page.locator('ul a[href="/tree/I2"]').evaluate((element) => { (element as HTMLElement).click(); (element as HTMLElement).click() })
  await expect(page).toHaveURL(/\/tree\/I2$/)
  await page.locator('ul a[href="/tree/I2"]').click()
  await page.getByRole('button', { name: 'Назад', exact: true }).click()
  await expect(page).toHaveURL(/\/tree\/I1$/)
  await expect(page.getByRole('button', { name: 'Назад', exact: true })).toBeDisabled()
  await page.getByRole('link', { name: 'До мене', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Назад', exact: true })).toBeDisabled()
})

test('home clears selected evidence and direct rooms have a safe home destination', async ({ page }) => {
  await page.goto('/person/I3')
  await expect(page.getByRole('button', { name: 'Назад', exact: true })).toBeDisabled()
  await page.getByRole('link', { name: 'До мене', exact: true }).click()
  await page.locator('svg [data-relationship-id]').first().press('Enter')
  await expect(page.getByTestId('relationship-details')).toBeVisible()
  await page.getByRole('link', { name: 'До мене', exact: true }).click()
  await expect(page.getByTestId('relationship-details')).toHaveCount(0)
  await page.getByRole('button', { name: 'Назад', exact: true }).click()
  await expect(page).toHaveURL(/\/person\/I3$/)
  await page.goForward()
  await expect(page.getByTestId('relationship-details')).toHaveCount(0)
})

test('one animation clock moves nodes and ports, and rapid recentering settles exactly', async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.clock.install({ time: new Date('2026-09-13T10:00:00Z') })
  await page.clock.pauseAt(new Date('2026-09-13T10:00:01Z'))
  await page.goto('/tree/I1')
  await expect(page.locator('svg [data-center="true"]')).toBeVisible()
  await page.clock.runFor(1000)
  await page.locator('ul a[href="/tree/I2"]').dispatchEvent('click')
  const layer = page.locator('[data-layer="coordinates"]')
  await expect(layer).toHaveAttribute('data-transition', 'moving')
  const center = page.locator('svg [data-center="true"]')
  const before = await center.getAttribute('transform')
  const edgeBefore = await page.locator('svg [data-relationship-id] path').first().getAttribute('d')
  await page.screenshot({ path: testInfo.outputPath('transition-start.png'), fullPage: true })
  await page.clock.runFor(160)
  expect(await center.getAttribute('transform')).not.toBe(before)
  expect(await page.locator('svg [data-relationship-id] path').first().getAttribute('d')).not.toBe(edgeBefore)
  await page.screenshot({ path: testInfo.outputPath('transition-middle.png'), fullPage: true })
  await page.locator('ul a[href="/tree/I3"]').dispatchEvent('click')
  await page.clock.runFor(500)
  await expect(layer).toHaveAttribute('data-transition', 'idle')
  await expect(center).toHaveAttribute('data-person-id', 'I3')
  for (const node of await page.locator('svg [data-appearance-id]').all()) await expect(node).toHaveAttribute('transform', 'translate(0 0)')
  expect(await page.locator('html').evaluate((element) => element.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.screenshot({ path: testInfo.outputPath('transition-finished.png'), fullPage: true })
})

test('reduced motion finishes immediately, including a preference change during movement', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/tree/I1')
  await page.locator('ul a[href="/tree/I2"]').dispatchEvent('click')
  await expect(page.locator('[data-layer="coordinates"]')).toHaveAttribute('data-transition', 'idle')
  await expect(page.locator('svg [data-center="true"]')).toHaveAttribute('transform', 'translate(0 0)')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.locator('ul a[href="/tree/I3"]').dispatchEvent('click')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.locator('[data-layer="coordinates"]')).toHaveAttribute('data-transition', 'idle')
  await expect(page.locator('svg [data-center="true"]')).toHaveAttribute('data-person-id', 'I3')
})
