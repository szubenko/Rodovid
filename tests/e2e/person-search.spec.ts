test('finds and centers all 45 people regardless of the visible generation', async ({ page }) => {
  // This is 45 complete search/recenter interactions, not one slow UI action.
  test.setTimeout(90_000)
  await page.goto('/tree/I1')
  await expect(page.locator('ul a[href^="/tree/"]')).toHaveCount(45)
  const people = await page.locator('ul a[href^="/tree/"]').evaluateAll((links) => links.map((link) => ({
    name: link.textContent!, id: link.getAttribute('href')!.split('/').pop()!,
  })))
  expect(people).toHaveLength(45)
  for (const person of people) {
    await page.getByLabel('Покоління', { exact: true }).selectOption('1')
    await page.getByRole('searchbox').fill(person.name.toLocaleUpperCase('uk'))
    await page.locator(`[data-search-person="${person.id}"]`).click()
    await expect(page.locator('svg [data-center="true"]')).toHaveAttribute('data-person-id', person.id)
    await expect(page.getByRole('searchbox')).toHaveValue('')
    const depth = page.getByLabel('Покоління', { exact: true })
    await expect(depth).toHaveValue((await depth.locator('option').last().getAttribute('value'))!)
  }
})

test('hidden results restore camera, collapsed branches and depth through Back and home', async ({ page }) => {
  await page.goto('/tree/I1')
  await page.getByLabel('Покоління', { exact: true }).selectOption('6')
  await page.getByText(/^Гілки карти ·/).click()
  await page.locator('[data-branch-appearance]').nth(1).getByRole('button').click()
  await page.getByRole('button', { name: 'Збільшити масштаб', exact: true }).click()
  await dragMap(page, -40, 0)
  const camera = page.locator('[data-layer="camera"]')
  const transform = await camera.getAttribute('transform')
  const nodes = await page.locator('svg [data-person-id]').count()
  const name = await page.locator('ul a[href="/tree/I25"]').textContent()
  await page.getByRole('searchbox').fill(name!)
  await page.locator('[data-search-person="I25"]').click()
  await expect(page).toHaveURL(/\/tree\/I25$/)
  await expect(camera).toHaveAttribute('transform', 'translate(0 0) scale(1)')
  await page.getByRole('button', { name: 'Назад', exact: true }).click()
  await expect(camera).toHaveAttribute('transform', transform!)
  await expect(page.locator('svg [data-person-id]')).toHaveCount(nodes)
  await expect(page.getByLabel('Покоління', { exact: true })).toHaveValue('6')
  await page.goForward()
  await expect(page).toHaveURL(/\/tree\/I25$/)
  await page.getByRole('link', { name: 'До мене', exact: true }).click()
  await expect(page).toHaveURL(/\/tree\/I1$/)
  await expect(camera).toHaveAttribute('transform', 'translate(0 0) scale(1)')
})

test('empty, no-match, clear and original spelling work at 320px', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/tree/I1')
  const search = page.getByRole('search')
  const input = page.getByRole('searchbox')
  await expect(search.getByRole('status')).toHaveText('Введіть ім’я або частину імені.')
  await input.fill(' \t ')
  await expect(search.getByRole('listitem')).toHaveCount(0)
  await input.fill('Сергій')
  await expect(search.getByRole('status')).toContainText('Нікого не знайдено')
  await input.press('Escape')
  await expect(input).toHaveValue('')
  await expect(input).toBeFocused()
  await input.fill('  ЗУБЕНКО   сегр  ')
  await expect(search.getByRole('listitem')).toHaveCount(1)
  await expect(search.locator('strong')).toHaveText('Сегрій Зубенко')
  await page.screenshot({ path: testInfo.outputPath('search-320.png'), fullPage: true })
  expect(await page.locator('html').evaluate((element) => element.scrollWidth)).toBeLessThanOrEqual(320)
  await search.getByRole('button', { name: 'Очистити пошук' }).click()
  await expect(input).toHaveValue('')
  await expect(input).toBeFocused()
})

test('prepared aliases, patronymics and namesakes support keyboard choice from a room', async ({ page }, testInfo) => {
  // Isolated synthetic response: never written to family data or the production build.
  const family = familyDataSchema.parse(fixture)
  family.datasetKind = 'family'
  const names = family.claims.filter((claim) => claim.field === 'name')
  names[1]!.value = { ...names[0]!.value }
  family.claims.push({ ...names[0]!, id: 'search-alias', isPrimary: false,
    value: { raw: 'Test /Alias/', display: 'Test Alias', given: 'Test', surname: 'Alias', patronymic: 'Петрівна' } })
  await page.route('**/data/family.json', (route) => route.fulfill({ json: family }))
  await page.goto('/person/I2')
  const input = page.getByRole('searchbox')
  const results = page.getByRole('search').getByRole('listitem')
  await input.fill('  ALIAS   петрів ')
  await expect(results).toHaveCount(1)
  await expect(results.first()).toContainText('Інші написання: Test Alias')
  await input.press('ArrowDown')
  await expect(page.locator('[data-search-person="I1"]')).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/\/tree\/I1$/)
  await expect(page.locator('h1')).toBeFocused()
  await page.getByRole('button', { name: 'Назад', exact: true }).click()
  await expect(page).toHaveURL(/\/person\/I2$/)
  await input.fill('тестова')
  await expect(results).toHaveCount(2)
  await expect(results.nth(0)).toContainText('нар. 1874 (є інші дати)')
  await expect(results.nth(1)).toContainText('Роки життя невідомі')
  await input.press('Enter')
  await expect(page).toHaveURL(/\/person\/I2$/)
  await expect(page.locator('[data-search-person="I1"]')).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.locator('[data-search-person="I2"]')).toBeFocused()
  await page.keyboard.press('ArrowUp')
  await expect(page.locator('[data-search-person="I1"]')).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.locator('[data-search-person="I2"]')).toBeFocused()
  await page.screenshot({ path: testInfo.outputPath('search-namesakes.png'), fullPage: true })
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/\/tree\/I2$/)
  await expect(page.locator('svg [data-center="true"]')).toHaveAttribute('data-person-id', 'I2')
})
