import { expect, test } from '@playwright/test'
import fixture from '../fixtures/data-contract/full.json' with { type: 'json' }
import { familyDataSchema } from '../../src/data/schema'

test('підказка зберігає всі факти, альтернативи й події та прокручується клавіатурою', async ({ page }, info) => {
  const family = familyDataSchema.parse(fixture)
  family.datasetKind = 'family'
  const provenance = family.people[0]!.provenance
  family.people[0]!.sex = 'M'
  family.people[0]!.externalIds.push({ system: 'AncestQuest-UID', value: 'E96EC68A3EF15647873C6F464E2D06D6426B' })
  family.claims.push({ id: 'name-latin', field: 'name', target: { kind: 'person', id: 'I1' },
    value: { raw: 'Testova /Osoba/', display: 'Testova Osoba' }, isPrimary: false, confidence: 'unassessed',
    explanation: 'Латинський варіант із GEDCOM ROMN; написання не перевірено.', provenance })
  family.claims.push({ id: 'person-description', field: 'description', target: { kind: 'person', id: 'I1' },
    value: 'Відомий опис людини', isPrimary: true, confidence: 'confirmed', provenance })
  family.events.push({ ...family.events[0]!, id: 'event-death', kind: 'death' })
  family.claims.push({ id: 'death-cause', field: 'cause', target: { kind: 'event', id: 'event-death' },
    value: 'Текст причини з тестового запису', isPrimary: false, confidence: 'hypothesis', provenance })
  family.events.push({ ...family.events[1]!, id: 'duplicate-marriage' })
  await page.route('**/data/family.json', route => route.fulfill({ json: family }))
  await page.goto('/tree/I1')
  const node = page.locator('[data-map-viewport] [data-center="true"]')
  await page.keyboard.press('Tab')
  await node.focus()
  const tooltip = page.getByRole('tooltip')
  await expect(tooltip).toBeVisible()
  await expect(node).toHaveAttribute('aria-describedby', await tooltip.getAttribute('id') ?? '')
  await expect(node.locator('title')).toHaveCount(0)
  const expectedClaims = family.claims.filter(claim => claim.target.id === 'I1' || family.events.some(event =>
    event.id === claim.target.id && event.participants.some(participant => participant.personId === 'I1')))
  expect(await tooltip.locator('[data-claim-id]').evaluateAll(elements => elements.map(element => element.getAttribute('data-claim-id')).sort()))
    .toEqual(expectedClaims.map(claim => claim.id).sort())
  await expect(tooltip.locator('[data-event-id]')).toHaveCount(4)
  await expect(tooltip).toContainText('1874')
  await expect(tooltip).toContainText('близько 1876')
  await expect(tooltip).toContainText('Testova Osoba')
  await expect(tooltip).not.toContainText('Альтернативний запис')
  await expect(tooltip).not.toContainText('Основний запис')
  await expect(tooltip).not.toContainText('Не оцінено')
  await expect(tooltip).not.toContainText('GEDCOM ROMN')
  await expect(tooltip).not.toContainText('Стать:')
  await expect(tooltip).not.toContainText('Життєвий статус')
  await expect(tooltip).not.toContainText('Прокручуйте')
  await expect(tooltip).not.toContainText('↓ —')
  await expect(tooltip).not.toContainText('AncestQuest-UID')
  await expect(tooltip).not.toContainText('E96EC68A3EF15647873C6F464E2D06D6426B')
  await expect(tooltip).toContainText('Гіпотеза')
  await expect(tooltip).toContainText('Відомий опис людини')
  await expect(tooltip).toContainText('Текст причини з тестового запису')
  await expect(tooltip).toContainText('example-1')
  await expect(tooltip).toContainText('Приклад Вигаданий')
  const box = await tooltip.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  expect(box!.y + box!.height).toBeLessThanOrEqual(page.viewportSize()!.height)
  const camera = page.locator('[data-layer="camera"]')
  const transform = await camera.getAttribute('transform')
  await page.keyboard.press('ArrowDown')
  const scroll = tooltip.locator('[data-tooltip-scroll]')
  await expect(scroll).toBeFocused()
  await page.keyboard.press('PageDown')
  await expect.poll(() => scroll.evaluate(element => element.scrollTop)).toBeGreaterThan(0)
  await expect(camera).toHaveAttribute('transform', transform!)
  await page.screenshot({ path: info.outputPath('tooltip-alternatives.png') })
  await page.keyboard.press('Escape')
  await expect(tooltip).toHaveCount(0)
  await expect(node).toBeFocused()
  await expect(node).not.toHaveAttribute('aria-describedby')
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/\/person\/I1$/)
})

test('картка наведення утримується під курсором, колесо прокручує лише її, Esc закриває', async ({ page, isMobile }, info) => {
  test.skip(isMobile, 'Наведення перевіряється мишею; дотик — окремим сценарієм.')
  await page.goto('/tree/I12')
  const node = page.locator('[data-map-viewport] [data-center="true"]')
  await node.hover()
  const tooltip = page.getByRole('tooltip')
  await expect(tooltip).toBeVisible()
  await tooltip.locator('[data-tooltip-scroll]').hover()
  const camera = page.locator('[data-layer="camera"]')
  const transform = await camera.getAttribute('transform')
  await page.mouse.wheel(0, 220)
  await expect.poll(() => tooltip.locator('[data-tooltip-scroll]').evaluate(element => element.scrollTop)).toBeGreaterThan(0)
  await expect(tooltip).toBeVisible()
  await expect(camera).toHaveAttribute('transform', transform!)
  await page.screenshot({ path: info.outputPath('tooltip-hover.png') })
  await page.keyboard.press('Escape')
  await expect(tooltip).toHaveCount(0)
  await node.hover()
  await expect(tooltip).toBeVisible()
  // Leaving the name and its card dismisses the preview.
  await page.mouse.move(1, 1)
  await expect(tooltip).toHaveCount(0)
})

