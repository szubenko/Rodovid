import { expect, test } from '@playwright/test'

test('separate parent buttons navigate directly with keyboard and preserve room history', async ({ page }, info) => {
  await page.goto('/person/I1')
  const doors = page.getByRole('region', { name: 'Переходи до рідних' })
  // The current export includes I1's spouse; only children are absent.
  await expect(doors.getByText('Записів у цьому родоводі немає.', { exact: true })).toHaveCount(0)
  const parents = doors.locator('div').filter({ has: page.getByRole('heading', { name: 'Батьки', exact: true }) }).last()
  await expect(parents.getByRole('button')).toHaveCount(2)
  await expect(doors.getByRole('button', { name: /^Обрати: батьки/ })).toHaveCount(0)
  await doors.screenshot({ path: info.outputPath('parent-buttons.png') })
  await parents.getByRole('button', { name: 'Ірина Іванівна Керницька', exact: true }).click()
  await expect(page).toHaveURL(/\/person\/I3$/)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: /^(?:← )?Назад$/ }).click()
  await expect(page).toHaveURL(/\/person\/I1$/)
  const father = parents.getByRole('button', { name: 'Петр Зубенко', exact: true })
  await father.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page).toHaveURL(/\/person\/I2$/)
  await expect(page.getByRole('heading', { level: 1 })).toBeFocused()
  await doors.getByRole('button', { name: 'Сегрій Зубенко', exact: true }).click()
  await expect(page).toHaveURL(/\/person\/I1$/)
  await page.getByRole('button', { name: /^(?:← )?Назад$/ }).click()
  await expect(page).toHaveURL(/\/person\/I2$/)
  await page.getByRole('link', { name: 'Показати на карті', exact: true }).click()
  await expect(page).toHaveURL(/\/tree\/I2$/)
})

test('children appear as direct buttons; rapid and reduced motion navigation', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/person/I12')
  const doors = page.getByRole('region', { name: 'Переходи до рідних' })
  const children = doors.getByRole('heading', { name: 'Діти', exact: true }).locator('..')
  await expect(children.getByRole('button')).toHaveCount(7)
  await expect(doors.getByRole('button', { name: /^Обрати:/ })).toHaveCount(0)
  await doors.getByRole('button', { name: 'Агафия Прокофиева Волинцова' }).evaluate((el: HTMLButtonElement) => { el.click(); el.click(); el.click() })
  await expect(page).toHaveURL(/\/person\/I11$/)
  await page.getByRole('button', { name: /^(?:← )?Назад$/ }).click()
  await expect(page).toHaveURL(/\/person\/I12$/)
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
