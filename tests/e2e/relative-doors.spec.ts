import { expect, test } from '@playwright/test'

test('zero, one and multiple relatives, close focus and back through rooms', async ({ page }) => {
  await page.goto('/person/I1')
  const doors = page.getByRole('region', { name: 'Переходи до рідних' })
  await expect(doors.getByText('Записів у цьому родоводі немає.', { exact: true })).toHaveCount(2)
  const parents = doors.getByRole('button', { name: 'Обрати: батьки (2)' })
  await parents.focus()
  await page.keyboard.press('Enter')
  const dialog = page.getByRole('dialog', { name: 'Обрати: батьки' })
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(parents).toBeFocused()
  await parents.click()
  await dialog.getByRole('button', { name: 'Петр Зубенко', exact: true }).click()
  await expect(page).toHaveURL(/\/person\/I2$/)
  await expect(page.getByRole('heading', { level: 1 })).toBeFocused()
  await doors.getByRole('button', { name: 'Сегрій Зубенко', exact: true }).click()
  await expect(page).toHaveURL(/\/person\/I1$/)
  await page.getByRole('button', { name: 'Назад', exact: true }).click()
  await expect(page).toHaveURL(/\/person\/I2$/)
  await page.getByRole('link', { name: 'Показати на карті', exact: true }).click()
  await expect(page).toHaveURL(/\/tree\/I2$/)
})

test('spouse and duplicate child records choose unique people; rapid and reduced motion navigation', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/person/I12')
  const doors = page.getByRole('region', { name: 'Переходи до рідних' })
  await expect(doors.getByRole('button', { name: 'Обрати: діти (7)' })).toBeVisible()
  await doors.getByRole('button', { name: 'Агафия Прокофиева Волинцова' }).evaluate((el: HTMLButtonElement) => { el.click(); el.click(); el.click() })
  await expect(page).toHaveURL(/\/person\/I11$/)
  await page.getByRole('button', { name: 'Назад', exact: true }).click()
  await expect(page).toHaveURL(/\/person\/I12$/)
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
