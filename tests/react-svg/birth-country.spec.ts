import { expect, test } from '@playwright/test'

test('only the radial diagram uses recorded birth country fills', async ({ page, isMobile }, testInfo) => {
  await page.goto('/tree/I1')
  const svg = page.getByRole('group', { name: /^Родина:/ })
  const legend = page.getByRole('group', { name: 'Країна народження', exact: true })
  await expect(legend).toContainText('як записано в родоводі')
  await expect(legend).toContainText('Galicia')
  await expect(legend).toContainText('Kazakhstan, Soviet Union')
  await expect(legend).toContainText('Ukraine, Soviet Union')
  await expect(svg.locator('[data-birth-country="Galicia"] > path').first()).toHaveCSS('fill', 'rgb(189, 227, 192)')
  await expect(svg.locator('[data-person-id="I1"]')).toHaveAttribute('data-birth-country', 'Kazakhstan, Soviet Union')
  await expect(svg.locator('[data-person-id="I1"] > circle')).toHaveCSS('fill', 'rgb(197, 230, 213)')
  await expect(svg.locator('[data-birth-country="Poland"] > path').first()).toHaveCSS('fill', 'rgb(243, 197, 206)')
  if (!isMobile) await svg.locator('[data-person-id="I1"]').hover()
  await expect(svg.locator('[data-person-id="I1"] > circle')).toHaveCSS('fill', 'rgb(197, 230, 213)')
  await page.screenshot({ path: testInfo.outputPath('birth-countries.png'), fullPage: true })
  await page.getByRole('link', { name: 'Горизонтальний родовід', exact: true }).click()
  await expect(legend).toHaveCount(0)
  await expect(page.locator('[data-birth-country]')).toHaveCount(0)
  await page.getByRole('link', { name: 'Вертикальний родовід', exact: true }).click()
  await expect(legend).toHaveCount(0)
  await expect(page.locator('[data-birth-country]')).toHaveCount(0)
})
