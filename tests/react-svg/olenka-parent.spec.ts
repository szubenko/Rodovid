import { expect, test } from '@playwright/test'

test('Оленка — дочка Якова й Наді; дві родини відповідають знімку FamilySearch', async ({ page }, info) => {
  await page.goto('/person/I10')
  const parents = page.locator('#relatives').getByRole('heading', { name: 'Батьки', exact: true }).locator('..')
  await expect(parents.getByRole('button')).toHaveCount(2)
  await expect(parents.getByRole('button', { name: 'Яков Макарович Зубенко', exact: true })).toBeVisible()
  await expect(parents.getByRole('button', { name: 'Надя', exact: true })).toBeVisible()
  await expect(page.locator('#biography').getByText('Ім’я: Оленка Яківна Зубенко', { exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath('olenka-parents.png'), fullPage: true })

  await parents.getByRole('button', { name: 'Яков Макарович Зубенко', exact: true }).click()
  await expect(page).toHaveURL(/\/person\/I5$/)
  const spouse = page.locator('#relatives').getByRole('heading', { name: 'Подружжя', exact: true }).locator('..')
  await expect(spouse.getByRole('button'))
    .toHaveText(['Надя', 'Ольга Петрівна Дейкало'])
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('#biography')).toContainText('23 березня 2015')
  const yakovChildren = page.locator('#relatives').getByRole('heading', { name: 'Діти', exact: true }).locator('..')
  await expect(yakovChildren.getByRole('button')).toHaveText(['Петр Зубенко', 'Оленка Яківна Зубенко', 'Николай Зубенко'])
  await expect(page.locator('#places + #relatives:last-child')).toHaveCount(1)
  await expect(page.getByRole('navigation', { name: 'Розділи кімнати' })).toHaveCount(0)
  expect(await page.locator('html').evaluate(el => el.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.locator('#relatives').screenshot({ path: info.outputPath('direct-relatives.png') })
  await spouse.getByRole('button', { name: 'Надя', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/\/person\/I87$/)
  const nadiaChildren = page.locator('#relatives').getByRole('heading', { name: 'Діти', exact: true }).locator('..')
  await expect(nadiaChildren.getByRole('button', { name: 'Оленка Яківна Зубенко', exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath('nadia-family.png'), fullPage: true })
  await page.goto('/person/I4')
  await expect(page).toHaveURL(/\/person\/I4$/)
  await expect(page.locator('#biography')).toContainText('22 грудня 2017')

  await page.goto('/person/I9')
  const children = page.locator('#relatives').getByRole('heading', { name: 'Діти', exact: true }).locator('..')
  await expect(children.getByRole('button', { name: 'Яков Макарович Зубенко', exact: true })).toBeVisible()
  await expect(children).not.toContainText('Оленка')
})
