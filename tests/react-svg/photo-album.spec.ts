import { expect, test } from '@playwright/test'

test('the album offers the gallery controls and returns to its origin', async ({ page }) => {
  await page.goto('/tree/I1')
  await page.getByRole('link', { name: 'Фотоальбом', exact: true }).click()
  await expect(page).toHaveURL(/\/photo-album(?:\?|$)/)
  const album = page.getByRole('dialog', { name: 'Перегляд фотографій' })
  await expect(album).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Фотогалерея' })).toBeVisible()
  await expect(page.getByLabel('Родина')).toBeVisible()
  await expect(page.getByRole('checkbox', { name: 'Не ідентиковані фотографії' })).toBeVisible()
  const counter = page.getByLabel('Номер фотографії')
  await expect(counter).toBeVisible()
  const stage = album.getByRole('button', { name: 'Наступне фото' }).locator('..')
  await expect(stage.locator('img')).toBeVisible()
  await stage.locator('img').evaluate(async img => { if (img instanceof HTMLImageElement) await img.decode() })
  const firstStage = await stage.boundingBox()
  await album.getByRole('button', { name: 'Наступне фото' }).click()
  await stage.locator('img').evaluate(async img => { if (img instanceof HTMLImageElement) await img.decode() })
  const secondStage = await stage.boundingBox()
  expect(secondStage?.x).toBeCloseTo(firstStage!.x, 0)
  expect(secondStage?.y).toBeCloseTo(firstStage!.y, 0)
  expect(secondStage?.width).toBeCloseTo(firstStage!.width, 0)
  expect(secondStage?.height).toBeCloseTo(firstStage!.height, 0)
  await expect(counter).toHaveValue('2')
  await expect.poll(() => new URL(page.url()).searchParams.get('photo')).toBeTruthy()
  const sharedUrl = page.url()
  await page.goBack()
  await expect(counter).toHaveValue('1')
  await page.goForward()
  await expect(counter).toHaveValue('2')
  await page.reload()
  await expect(page).toHaveURL(sharedUrl)
  await expect(counter).toHaveValue('2')
  await expect(album.getByRole('complementary', { name: 'Опис фотографії' })).toBeVisible()
  await expect(album.getByRole('button', { name: 'Збільшити' })).toHaveCount(0)
  await expect(album.getByRole('button', { name: 'Сховати опис' })).toHaveCount(0)
  await expect(album.getByRole('button', { name: 'Закрити перегляд' })).toHaveCount(0)
  const openViewer = album.getByRole('button', { name: /^Відкрити повноекранний перегляд:/ })
  await openViewer.click()
  const viewer = page.getByRole('dialog', { name: 'Перегляд фотографій' })
  await expect(viewer.getByLabel('Номер фотографії')).toHaveValue('2')
  await viewer.getByRole('button', { name: 'Наступне фото' }).click()
  await expect(viewer.getByLabel('Номер фотографії')).toHaveValue('3')
  await expect.poll(() => new URL(page.url()).searchParams.get('viewer')).toBe('1')
  await page.reload()
  await expect(viewer.getByLabel('Номер фотографії')).toHaveValue('3')
  await viewer.getByRole('button', { name: 'Закрити перегляд' }).click()
  await expect(counter).toHaveValue('3')
  await page.getByRole('checkbox', { name: 'Не ідентиковані фотографії' }).check()
  await page.getByLabel('Родина').selectOption('zubenko')
  await expect(page.getByRole('checkbox', { name: 'Не ідентиковані фотографії' })).toBeChecked()
  await expect(page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).resolves.toBe(true)
  await page.getByRole('link', { name: 'До мене' }).click()
  await expect(page).toHaveURL(/\/tree\/I1$/)
})
