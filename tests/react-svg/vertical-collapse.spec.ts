import { test, expect } from '@playwright/test'

for (const [center, siblings] of [['I12', ['I25', 'I21', 'I23', 'I76', 'I77']], ['I4', ['I71', 'I72', 'I73', 'I74']]] as const) {
  test(`бокова стрілка ${center} не відкриває згорнутих предків`, async ({ page }, testInfo) => {
    await page.goto(`/vertical-design/${center}`)
    await expect(page.locator(`[data-person-id="${center}"]`)).toBeVisible()
    const initial = await page.locator('[data-person-id]').count()
    const top = page.locator(`[data-ancestor-person-id="${center}"]`)
    const side = page.locator(`[data-sibling-person-id="${center}"]`)
    await top.press('Enter')
    await expect(page.locator('[data-person-id]')).toHaveCount(1)
    await side.press('Enter')
    for (const compact of [false, true]) {
      if (compact) await page.getByRole('button', { name: 'Компактні картки', exact: true }).click()
      await expect(top).toHaveAttribute('aria-expanded', 'false')
      await expect(top.locator('path')).toHaveAttribute('d', 'M-8 4 0-4 8 4')
      await expect(side).toHaveAttribute('aria-expanded', 'true')
      await expect(page.locator('[data-person-id]')).toHaveCount(siblings.length + 1)
      for (const id of siblings) await expect(page.locator(`[data-person-id="${id}"]`)).toHaveCount(1)
    }
    await page.locator(`[data-person-id="${center}"]`).press('Enter')
    await expect(page).toHaveURL(new RegExp(`/person/${center}$`))
    await page.goBack()
    await expect(top).toHaveAttribute('aria-expanded', 'false')
    await expect(side).toHaveAttribute('aria-expanded', 'true')
    await page.getByRole('button', { name: 'Вмістити карту', exact: true }).click()
    await page.screenshot({ path: testInfo.outputPath('siblings-with-ancestors-folded.png'), fullPage: true })
    const download = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Зберегти PNG', exact: true }).click()
    await (await download).saveAs(testInfo.outputPath('siblings-with-ancestors-folded-export.png'))
    await side.press('Enter')
    await expect(page.locator('[data-person-id]')).toHaveCount(1)
    await expect(top).toHaveAttribute('aria-expanded', 'false')
    await top.press('Enter')
    await expect(page.locator('[data-person-id]')).toHaveCount(initial)
  })
}

test('верхні стрілки лише на основній предковій лінії та перераховуються при зміні центру', async ({ page }, testInfo) => {
  await page.goto('/vertical-design/I12')
  await expect(page.locator('[data-person-id="I12"]')).toBeVisible()
  await page.locator('[data-sibling-person-id="I12"]').press('Enter')
  for (const compact of [false, true]) {
    if (compact) await page.getByRole('button', { name: 'Компактні картки', exact: true }).click()
    await expect(page.locator('[data-ancestor-person-id="I12"]')).toHaveCount(1)
    for (const id of ['I25', 'I21', 'I23', 'I76', 'I77']) {
      await expect(page.locator(`[data-person-id="${id}"]`)).toHaveCount(1)
      await expect(page.locator(`[data-ancestor-person-id="${id}"]`)).toHaveCount(0)
    }
    expect(await page.locator('[data-ancestor-person-id]').evaluateAll(arrows => arrows.every(arrow => {
      const id = arrow.getAttribute('data-ancestor-person-id')
      return arrow.closest('svg')!.querySelector(`[data-person-id="${id}"]`)!.getAttribute('data-direct-line') === 'true'
    }))).toBe(true)
  }
  await page.getByRole('button', { name: 'Вмістити карту', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('main-line-arrows-only.png'), fullPage: true })
  await page.locator('[data-person-id="I25"]').press('Enter')
  await expect(page).toHaveURL(/\/vertical-design\/I25$/)
  await expect(page.locator('[data-ancestor-person-id="I25"]')).toHaveAttribute('aria-expanded', 'true')
})

test('верхня стрілка складає лише свою гілку, утримує картку й повертає бокові розгортання', async ({ page }, testInfo) => {
  await page.goto('/vertical-design/I1')
  await expect(page.locator('[data-person-id="I1"]')).toBeVisible()
  await page.locator('[data-sibling-person-id="I2"]').press('Enter')
  await page.locator('[data-sibling-person-id="I4"]').press('Enter')
  const initial = await page.locator('[data-person-id]').evaluateAll(nodes => nodes.map(node => node.getAttribute('data-person-id')).sort())
  const arrow = page.locator('[data-ancestor-person-id="I2"]')
  await expect(arrow).toHaveAttribute('aria-expanded', 'true')
  await expect(arrow.locator('path')).toHaveAttribute('d', 'M-8-4 0 4 8-4')
  expect(await arrow.evaluate(node => {
    const card = node.closest('svg')!.querySelector('[data-person-id="I2"] > rect')!.getBoundingClientRect()
    const b = node.getBoundingClientRect()
    return b.y + b.height / 2 < card.top
  })).toBe(true)
  const anchor = page.locator('[data-person-id="I2"] > rect')
  const before = await anchor.boundingBox()
  await arrow.press('Enter')
  await expect(arrow).toHaveAttribute('aria-expanded', 'false')
  await expect(arrow.locator('path')).toHaveAttribute('d', 'M-8 4 0-4 8 4')
  for (const id of ['I5', 'I4', 'I9', 'I6', 'I71']) await expect(page.locator(`[data-person-id="${id}"]`)).toHaveCount(0)
  for (const id of ['I1', 'I2', 'I3', 'I28', 'I29', 'I10', 'I27']) await expect(page.locator(`[data-person-id="${id}"]`)).toHaveCount(1)
  const after = await anchor.boundingBox()
  expect(Math.abs(before!.x - after!.x)).toBeLessThan(1)
  expect(Math.abs(before!.y - after!.y)).toBeLessThan(1)
  await page.getByRole('button', { name: 'Вмістити карту', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('paternal-branch-folded.png'), fullPage: true })
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Зберегти PNG', exact: true }).click()
  await (await download).saveAs(testInfo.outputPath('folded-branch-export.png'))
  await page.getByRole('button', { name: 'Компактні картки', exact: true }).click()
  await expect(arrow).toHaveAttribute('aria-expanded', 'false')
  await arrow.press('Space')
  expect(await page.locator('[data-person-id]').evaluateAll(nodes => nodes.map(node => node.getAttribute('data-person-id')).sort())).toEqual(initial)
  await expect(page.locator('[data-sibling-person-id="I4"]')).toHaveAttribute('aria-expanded', 'true')
})

test('згортання всіх предків, відновлення історії та керування мишею або дотиком', async ({ page }, testInfo) => {
  await page.goto('/vertical-design/I1')
  await expect(page.locator('[data-person-id="I1"]')).toBeVisible()
  await page.getByRole('button', { name: 'До центру', exact: true }).click()
  const initial = await page.locator('[data-person-id]').count()
  const arrow = page.locator('[data-ancestor-person-id="I1"]')
  await arrow.click()
  await expect(page.locator('[data-person-id]')).toHaveCount(1)
  await expect(arrow).toHaveAttribute('aria-expanded', 'false')
  await expect(page).toHaveURL(/\/vertical-design\/I1$/)
  await page.screenshot({ path: testInfo.outputPath('all-ancestors-folded.png'), fullPage: true })
  await page.locator('[data-person-id="I1"]').press('Enter')
  await expect(page).toHaveURL(/\/person\/I1$/)
  await page.goBack()
  await expect(page.locator('[data-person-id]')).toHaveCount(1)
  await expect(arrow).toHaveAttribute('aria-expanded', 'false')
  await arrow.click()
  await expect(page.locator('[data-person-id]')).toHaveCount(initial)
  await page.goto('/vertical-design/I83')
  await expect(page.locator('[data-person-id="I83"]')).toBeVisible()
  await expect(page.locator('[data-ancestor-person-id]')).toHaveCount(0)
})
