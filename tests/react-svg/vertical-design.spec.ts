import { test, expect } from '@playwright/test'

test('окрема копія, компактна геометрія, довгі імена та історія перегляду', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/vertical/I1')
  await expect(page.locator('[data-person-id="I1"]')).toBeVisible()
  const original = page.locator('[data-layer="layout"]')
  const ids = await page.locator('[data-person-id]').evaluateAll(nodes => nodes.map(node => node.getAttribute('data-person-id')))
  const oldBounds = await original.evaluate(node => { const b = (node as SVGGraphicsElement).getBBox(); return { width: b.width, height: b.height } })
  await page.getByRole('link', { name: 'Вертикальний · новий дизайн', exact: true }).click()
  await expect(page).toHaveURL(/\/vertical-design\/I1$/)
  const section = page.locator('[data-card-design="portrait"]')
  await expect(section).toHaveAttribute('data-card-density', 'full')
  expect(await page.locator('[data-person-id]').evaluateAll(nodes => nodes.map(node => node.getAttribute('data-person-id')))).toEqual(ids)
  const bounds = () => original.evaluate(node => { const b = (node as SVGGraphicsElement).getBBox(); return { width: b.width, height: b.height } })
  const full = await bounds()
  expect(full.width).toBeLessThan(oldBounds.width)
  await page.getByRole('button', { name: 'До центру', exact: true }).click()
  await page.locator('[data-center="true"][data-person-id]').screenshot({ path: testInfo.outputPath('portrait-owner.png') })
  await page.getByRole('button', { name: 'Вмістити карту', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('portrait-full.png'), fullPage: true })
  await page.getByRole('button', { name: 'Компактні картки', exact: true }).click()
  await expect(section).toHaveAttribute('data-card-density', 'compact')
  const compact = await bounds()
  expect(compact.width).toBeLessThan(full.width)
  expect(compact.height).toBeLessThan(full.height)
  await page.getByRole('button', { name: 'Вмістити карту', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('portrait-compact.png'), fullPage: true })
  await page.getByRole('button', { name: 'До центру', exact: true }).click()
  expect(await page.locator('[data-person-id]').evaluateAll(nodes => nodes.every(node => {
    const card = node.querySelector('rect')!.getBoundingClientRect()
    return [...node.querySelectorAll('text')].every(text => {
      const b = text.getBoundingClientRect()
      return b.left >= card.left && b.right <= card.right && b.top >= card.top && b.bottom <= card.bottom
    })
  }))).toBe(true)
  const camera = await page.locator('[data-layer="camera"]').getAttribute('transform')
  await page.locator('[data-center="true"][data-person-id]').focus()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/\/person\/I1$/)
  await page.goBack()
  await expect(section).toHaveAttribute('data-card-density', 'compact')
  await expect(page.locator('[data-layer="camera"]')).toHaveAttribute('transform', camera!)
  await page.getByRole('button', { name: 'Назад до попереднього перегляду', exact: true }).click()
  await expect(page).toHaveURL(/\/vertical\/I1$/)
  expect(await bounds()).toEqual(oldBounds)
  expect(errors).toEqual([])
  console.log(JSON.stringify({ oldBounds, full, compact }))
})

test('повний родовід, скіни, зміна центру й експорт портретів у PNG', async ({ page }, testInfo) => {
  test.setTimeout(60_000)
  await page.goto('/vertical-design/I1')
  const generations = page.getByLabel('Покоління', { exact: true })
  await generations.selectOption((await generations.locator('option').last().getAttribute('value'))!)
  const people = await page.locator('[data-person-id]').count()
  await expect(page.locator('[data-lane="children"], [data-lane="spouses"], [data-lane="relatives"]')).toHaveCount(0)
  for (const compact of [false, true]) {
    if (compact) await page.getByRole('button', { name: 'Компактні картки', exact: true }).click()
    expect(await page.locator('[data-person-id]').count()).toBe(people)
    await page.getByRole('button', { name: 'Вмістити карту', exact: true }).click()
    await page.screenshot({ path: testInfo.outputPath(`ancestors-${compact ? 'compact' : 'full'}.png`), fullPage: true })
    expect(await page.locator('[data-person-id]').evaluateAll(nodes => nodes.every(node => {
      const card = node.querySelector('rect')!.getBoundingClientRect()
      return [...node.querySelectorAll('text')].every(text => {
        const b = text.getBoundingClientRect()
        return b.left >= card.left - .1 && b.right <= card.right + .1 && b.top >= card.top - .1 && b.bottom <= card.bottom + .1
      })
    }))).toBe(true)
  }
  await generations.selectOption('1')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Зберегти PNG', exact: true }).click()
  const result = await download
  expect(result.suggestedFilename()).toBe('rodovid-vertical-design-I1.png')
  await result.saveAs(testInfo.outputPath('portrait-export.png'))
  await page.getByRole('button', { name: 'До центру', exact: true }).click()
  await page.locator('[data-person-id="I2"]').focus()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/\/vertical-design\/I2$/)
  await expect(page.locator('[data-card-design="portrait"]')).toHaveAttribute('data-card-density', 'compact')
  await expect(page.locator('[data-center="true"][data-person-id]')).toHaveAttribute('data-person-id', 'I2')
  await expect(page.locator('[data-person-id="I1"]')).toHaveCount(0)
})
